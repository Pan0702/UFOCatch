void CAABB::MakeAABB(const VECTOR3& v1, const VECTOR3& v2, const FLOAT& r)
{
	if (v1.x > v2.x) {
		m_vMin.x = v2.x;
	}
	else {
		m_vMin.x = v1.x;
	}
	m_vMin.x -= r;

	if (v1.y > v2.y) {
		m_vMin.y = v2.y;
	}
	else {
		m_vMin.y = v1.y;
	}
	m_vMin.y -= r;

	if (v1.z > v2.z) {
		m_vMin.z = v2.z;
	}
	else {
		m_vMin.z = v1.z;
	}
	m_vMin.z -= r;

	if (v1.x < v2.x) {
		m_vMax.x = v2.x;
	}
	else {
		m_vMax.x = v1.x;
	}
	m_vMax.x += r;

	if (v1.y < v2.y) {
		m_vMax.y = v2.y;
	}
	else {
		m_vMax.y = v1.y;
	}
	m_vMax.y += r;

	if (v1.z < v2.z) {
		m_vMax.z = v2.z;
	}
	else {
		m_vMax.z = v1.z;
	}
	m_vMax.z += r;
}
